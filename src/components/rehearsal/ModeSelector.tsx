export default function ModeSelector({
  currentMode,
  onSelectMode,
  onClose,
}: ModeSelectorProps) {
  const handleSelect = useCallback(
    (mode: RehearsalMode) => {
      onSelectMode(mode);
      onClose?.();
    },
    [onSelectMode, onClose]
  );

  const handleBackdropClick = (e: React.MouseEvent) => {
    if (e.target === e.currentTarget) {
      onClose?.();
    }
  };

  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 backdrop-blur-sm p-4"
      onClick={handleBackdropClick}
    >
      <div className="bg-surface border border-border rounded-2xl w-full max-w-3xl max-h-[85vh] overflow-y-auto">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-border">
          <h2 className="text-xl font-bold text-foreground">
            Practice Mode
          </h2>
          {onClose && (
            <button
              onClick={onClose}
              className="w-9 h-9 flex items-center justify-center rounded-full hover:bg-surface-light text-muted hover:text-foreground transition-colors"
            >
              <svg
                className="w-5 h-5"
                fill="none"
                viewBox="0 0 24 24"
                strokeWidth={1.5}
                stroke="currentColor"
              >
                <path
                  strokeLinecap="round"
                  strokeLinejoin="round"
                  d="M6 18 18 6M6 6l12 12"
                />
              </svg>
            </button>
          )}
        </div>

        {/* Mode Grid */}
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 p-6">
          {MODES.map((mode) => {
            const isActive = currentMode === mode.id;
            return (
              <button
                key={mode.id}
                onClick={() => handleSelect(mode.id)}
                className={`flex items-start gap-4 p-4 rounded-xl text-left transition-all ${
                  isActive
                    ? "bg-accent/10 border-2 border-accent shadow-lg shadow-accent/10"
                    : "bg-surface-light border-2 border-transparent hover:border-border hover:bg-border/50"
                }`}
              >
                <div
                  className={`shrink-0 w-12 h-12 rounded-xl flex items-center justify-center ${
                    isActive
                      ? "bg-accent/20 text-accent-light"
                      : "bg-surface text-muted"
                  }`}
                >
                  {mode.icon}
                </div>
                <div className="min-w-0">
                  <div className="flex items-center gap-2">
                    <p
                      className={`font-semibold text-base ${
                        isActive ? "text-accent-light" : "text-foreground"
                      }`}
                    >
                      {mode.name}
                    </p>
                    {isActive && (
                      <span className="text-xs bg-accent/20 text-accent-light px-2 py-0.5 rounded-full font-medium">
                        Active
                      </span>
                    )}
                    {mode.tag && !isActive && (
                      <span className="text-xs bg-success/20 text-success px-2 py-0.5 rounded-full font-medium">
                        {mode.tag}
                      </span>
                    )}
                  </div>
                  <p className="text-sm text-muted mt-1 leading-snug">
                    {mode.description}
                  </p>
                </div>
              </button>
            );
          })}
        </div>
      </div>
    </div>
  );
}
